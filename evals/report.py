"""Run the evals and write evals/REPORT.md from the rows they write (evals/RULES.md, "Measured, never claimed").

    uv run python evals/report.py                          # runs `pytest evals -m "not live"`, then writes the report
    uv run python evals/report.py --from run.jsonl         # writes the report from an earlier run's rows
    uv run python evals/report.py --out evals/REPORT.md --keep evals/results/final.jsonl

REPORT.md quotes only numbers found in the rows. Anything the run could not do is listed as not run.
"""

import argparse
import json
import os
import subprocess
import sys
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
DEFAULT_OUT = HERE / "REPORT.md"

Row = dict[str, Any]


def read_rows(path: Path) -> list[Row]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def run_pytest(results: Path, extra: list[str]) -> int:
    env = {**os.environ, "ECOZONE_EVAL_RESULTS": str(results)}
    cmd = ["uv", "run", "pytest", "evals", "-m", "not live", "-rxXs", *extra]
    sys.stdout.write("running: " + " ".join(cmd) + "\n")
    return subprocess.run(cmd, cwd=REPO, env=env, check=False).returncode


def short(nodeid: str) -> str:
    return nodeid.split("/")[-1]


def fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:,.3f}".rstrip("0").rstrip(".") if abs(value) < 1000 else f"{value:,.0f}"
    if isinstance(value, dict):
        return ", ".join(f"{k}: {fmt(v)}" for k, v in value.items())  # pyright: ignore[reportUnknownVariableType]
    if isinstance(value, list):
        return ", ".join(fmt(v) for v in value)  # pyright: ignore[reportUnknownVariableType]
    return str(value)


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def measures(rows: list[Row], prefix: str) -> list[Row]:
    return [r for r in rows if r["result"] == "measured" and r["test"].startswith(prefix)]


def build(rows: list[Row]) -> str:
    outcomes = [r for r in rows if r["subject"] == "outcome"]
    for o in outcomes:
        o["result"] = {"passed": "pass", "failed": "fail"}.get(o["result"], o["result"])
    session = {r["subject"]: r["value"] for r in rows if r["test"] == "session" and r["result"] == "measured"}
    bundle: dict[str, Any] = session.get("bundle", {})
    machine: dict[str, Any] = session.get("machine", {})
    first = rows[0] if rows else {}
    commit = str(first.get("commit", "unknown"))
    dirty = bool(first.get("dirty", False))
    run_at = min((r["run_at"] for r in rows), default="unknown")
    counts = defaultdict(int)
    for o in outcomes:
        counts[o["result"]] += 1

    out: list[str] = []
    out.append("# Evaluation report")
    out.append("")
    out.append(
        "Generated by `evals/report.py` from the rows a real run wrote. Every number below was produced by an eval in "
        "that run; nothing is a target or an estimate. Scores are the engine's 0-100 heuristic indices (VCI, HEI, GCS, "
        "PSS) and the Area Cooling Score (ACS)."
    )
    out.append("")
    out.append(f"- **Commit:** `{commit}`{' (working tree had uncommitted changes)' if dirty else ''}")
    out.append(f"- **Run at:** {run_at}")
    out.append(
        f"- **Bundle:** {bundle.get('name')} (`{bundle.get('area_id')}`), version `{bundle.get('bundle_version')}`, "
        f"reference date {bundle.get('reference_date')}, pipeline commit `{bundle.get('pipeline_git_sha')}`, "
        f"settings hash `{str(bundle.get('settings_hash'))[:12]}`"
    )
    out.append(f"- **Bundle source:** {bundle.get('bundle_note')}")
    c = bundle.get("counts") or {}
    out.append(
        f"- **Bundle size:** {fmt(c)}; blocks split {bundle.get('tune_blocks')} tune / "
        f"{bundle.get('test_blocks')} test "
        "(range results are reported on the test blocks; nothing here was tuned on either half)"
    )
    out.append(f"- **Machine:** {machine.get('platform')}, {machine.get('cpus')} CPUs, Python {machine.get('python')}")
    out.append(
        "- **Results by outcome:** "
        + ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
        + f" ({len(outcomes)} evals)"
    )
    if bundle.get("bundle_kind") == "tiny":
        out.append("")
        out.append("> **This report was produced on the tiny CI fixture, not on the Deccan bundle.**")
    out.append("")

    out.append("## Results")
    out.append("")
    order = {"fail": 0, "xpass": 1, "xfail": 2, "skip": 3, "pass": 4}
    rows_out = [
        [f"`{short(o['test'])}`", o["result"], f"{o['value']:.1f} seconds"]
        for o in sorted(outcomes, key=lambda o: (order.get(o["result"], 9), o["test"]))
    ]
    out += table(["Eval", "Result", "Time"], rows_out)
    out.append("")

    problems = [o for o in outcomes if o["result"] in ("fail", "xfail", "xpass")]
    out.append("## Failures and findings")
    out.append("")
    if not problems:
        out.append("No eval failed.")
    shown: set[tuple[str, str, str]] = set()
    for o in problems:
        out.append(f"### `{short(o['test'])}`: {o['result']}")
        out.append("")
        out.append(str(o.get("detail") or "(no detail recorded)"))
        out.append("")
        note = ANALYSIS.get(short(o["test"]).split("::")[-1].split("[")[0])
        if note:
            out.append(f"Analysis (from reading the code, not measured): {note}")
            out.append("")
        group = _group(o["test"])
        related = [
            m
            for m in rows
            if m["result"] == "measured"
            and m["test"].split(".")[0] == group
            and (group, m["test"], m["subject"]) not in shown
        ]
        for m in related:
            shown.add((group, m["test"], m["subject"]))
            out.append(f"- measured `{m['test']}` / `{m['subject']}`: {fmt(m['value'])}")
        out.append("")

    out.append("## Gemini vs greedy (offline rule proposer, not Gemini)")
    out.append("")
    out.append(
        "The search loop was run with `ECOZONE_LLM=fake`: the offline rule proposer stands in for the model, so these "
        "rows describe the loop and scorer, not Gemini. There is no pass mark. ACS is the area cooling score after the "
        "plan (higher is better); baseline is the area before any change. Outcome compares the best valid AI plan with "
        "the greedy plan by ACS (a difference under 0.05 is a tie). `Loop verdict` is the search's own "
        "`gemini_beat_greedy`, which also counts a greedy plan that breaks a rule as beaten."
    )
    out.append("")
    fake = measures(rows, "gemini_vs_greedy.fake")
    if fake:
        trs: list[list[str]] = []
        for m in fake:
            v = m["value"]
            trs.append(
                [
                    f"`{m['subject']}`",
                    f"{v['budget_inr']:,.0f}",
                    f"{v['quick_win_share_pct']:g}%",
                    f"{v['baseline_acs']:.2f}",
                    f"{v['greedy_acs']:.2f}"
                    + ("" if v["greedy_valid"] else f" (invalid: {v['greedy_invalid_reason']})"),
                    "none valid" if v["ai_acs"] is None else f"{v['ai_acs']:.2f}",
                    "n/a" if v["delta"] is None else f"{v['delta']:+.2f}",
                    v["outcome"],
                    str(v["reported_gemini_beat_greedy"]),
                    f"{v['ai_valid_candidates']}/{v['ai_candidates']}",
                ]
            )
        out += table(
            [
                "Case",
                "Budget (INR)",
                "Quick-win share",
                "Baseline ACS",
                "Greedy ACS",
                "AI ACS",
                "Delta",
                "Outcome",
                "Loop verdict",
                "Valid/all AI candidates",
            ],
            trs,
        )
        out.append("")
        for m in fake:
            reasons = m["value"].get("ai_invalid_reasons") or {}
            out.append(
                f"- `{m['subject']}`: AI candidates not valid: {fmt(reasons) if reasons else 'none'}; "
                f"rounds run: {m['value']['rounds']}; greedy plan cost {m['value']['greedy_cost_inr']:,} INR"
            )
    else:
        out.append("Not run.")
    out.append("")
    live = measures(rows, "gemini_vs_greedy.live")
    out.append("### Live Gemini")
    out.append("")
    if live:
        for m in live:
            out.append(f"- `{m['subject']}`: {fmt(m['value'])}")
    else:
        out.append(
            "**Not run.** The live Gemini evals (`evals/test_live_gemini.py`, marker `live`) need Vertex AI "
            "credentials "
            "and `ECOZONE_LLM=gemini`; this run was offline. No Gemini number is reported."
        )
    out.append("")

    prot = measures(rows, "protect_search.fake")
    if prot:
        out.append("### Protect design search (offline rule proposer)")
        out.append("")
        out.append("Worst change for each option (lower is better) and the share of floor area kept. No pass mark.")
        out.append("")
        ptr = []
        for m in prot:
            v = m["value"]
            ptr.append(
                [f"`{m['subject']}`"]
                + [
                    f"{v[k]['worst_change']:.2f} ({v[k]['risk_label']}), {v[k]['floor_area_pct']:.0f}% floor area"
                    for k in ("A", "B", "C")
                ]
            )
        out += table(["Parcel", "A (as proposed)", "B", "C"], ptr)
        out.append("")

    out.append("## Speed")
    out.append("")
    out.append(
        "Wall time with `time.perf_counter`, 20 repeated runs after one warm-up (10 for shadows and the empty "
        "rescore); "
        "targets are the numbers in docs/ENGINEERING_RULES.md section 8. Greedy and the search are single runs."
    )
    out.append("")
    sp = [m for m in rows if m["result"] == "measured" and m["test"].startswith("speed.rescore")]
    sp += measures(rows, "speed.shadows") + measures(rows, "speed.diagnosis")
    srows: list[list[str]] = []
    for m in sp:
        v = m["value"]
        srows.append(
            [
                f"{m['test'].split('.')[1]}: {m['subject']}",
                f"{v['p50_ms']:,.0f}",
                f"{v['p95_ms']:,.0f}",
                f"{v['min_ms']:,.0f} to {v['max_ms']:,.0f}",
                f"{v['target_ms']:,.0f}" if "target_ms" in v else "none",
                ("within" if v["p95_ms"] <= v["target_ms"] else "over") if "target_ms" in v else "",
            ]
        )
    if srows:
        out += table(["Step", "p50 (ms)", "p95 (ms)", "Range (ms)", "Target (ms)", "p95 vs target"], srows)
    out.append("")
    other: list[list[str]] = []
    for m in measures(rows, "speed.load_bundle") + measures(rows, "speed.greedy") + measures(rows, "speed.search"):
        other.append([f"{m['test'].split('.')[1]}: {m['subject']}", fmt(m["value"]), str(m.get("detail") or "")])
    if other:
        out += table(["Step", "Measured", "Note"], other)
        out.append("")

    out.append("## Other measured values")
    out.append("")
    skip_groups = ("session", "gemini_vs_greedy", "protect_search", "speed")
    groups: dict[str, list[Row]] = defaultdict(list)
    for m in rows:
        if m["result"] == "measured" and not m["test"].startswith(skip_groups):
            groups[m["test"]].append(m)
    for g in sorted(groups):
        out.append(f"**{g}**")
        out.append("")
        for m in groups[g]:
            note = f" ({m['detail']})" if m.get("detail") else ""
            out.append(f"- `{m['subject']}`: {fmt(m['value'])}{note}")
        out.append("")

    out.append("## Not run")
    out.append("")
    out.append(
        "- **Live Gemini evals** (Gemini vs greedy with the real model, grounding and tool-order runs on Gemini): "
        "need Vertex AI credentials; not run here."
    )
    skipped = (bundle.get("skipped_steps")) or []
    out.append(
        "- **Heat check** (`pipeline/validate.py`: heat index against measured surface temperature on the held-out "
        "blocks): not run. The bundle's pipeline skipped steps "
        f"`{', '.join(skipped) or 'none'}`, so there is no surface "
        "temperature layer in it, and Earth Engine access is not available here. No correlation is reported."
    )
    skips = [o for o in outcomes if o["result"] == "skip"]
    for o in skips:
        out.append(f"- `{short(o['test'])}` was skipped: {o.get('detail') or 'no reason recorded'}")
    out.append("")
    out.append("## How the search was driven")
    out.append("")
    out.append(
        "The agents' search loop calls `summary` and `layer`, which are not implemented on this branch, and the evals "
        "must not call them. `evals/evalkit/adapter.py` answers those two reads from the loaded area and meta.json and "
        "passes everything else to the engine's public API unchanged. `rescore` is never cached. Greedy and the "
        "per-site results are computed once in worker processes by the same engine functions, to save wall time; "
        "sites the canopy rule rejects are reported to the loop as not usable (the engine's own `single_site` "
        "raises InvalidChangeError for them, checked on the tiny fixture, which the loop's site catalog does not "
        "expect). Search runs use a long time limit so "
        "the wall clock cannot change what a run does."
    )
    out.append("")
    return "\n".join(out) + "\n"


ANALYSIS = {
    "test_search_returns_a_valid_plan": (
        "engine/greedy.py stops adding quick wins at the quick-win share in its first phase and only ends above the "
        "share if later additions happen to be quick wins, so it can finish a fraction of a percent under; "
        "agents/repair.py then marks that plan invalid ('Below the quick-win share') because it requires the full "
        "share. When the greedy plan is invalid the loop needs a valid AI plan; the offline proposer's candidates are "
        "dropped as repeats of greedy's own site set or fall under the share too. The shortfall is in the engine's "
        "greedy or in how the loop reads the share, which is an engine/agents decision, not something this eval "
        "should relax."
    ),
    "test_repair_rescore_latency": (
        "baseline chunk shading alone takes about half of an empty rescore (see the diagnosis row in Speed), and "
        "rescore runs it twice."
    ),
}


def _group(nodeid: str) -> str:
    name = short(nodeid).split("::")[0]
    return name.removeprefix("test_").removesuffix(".py").split("_")[0]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="source", type=Path, help="write the report from this JSONL instead of running")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--keep", type=Path, help="also copy the rows to this path (the committed final run)")
    ap.add_argument("pytest_args", nargs="*", help="extra arguments for pytest")
    args = ap.parse_args()

    if args.source:
        results = args.source
        code = 0
    else:
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        results = HERE / "results" / f"run-{stamp}.jsonl"
        code = run_pytest(results, args.pytest_args)
    rows = read_rows(results)
    if not rows:
        sys.stderr.write("no rows were written; nothing to report\n")
        return 2
    args.out.write_text(build(rows))
    if args.keep:
        args.keep.write_text(results.read_text())
    sys.stdout.write(f"wrote {args.out} from {results} (pytest exit code {code})\n")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
