"""Run the evals and write evals/REPORT.md from the rows they write (evals/RULES.md, "Measured, never claimed").

    uv run python evals/report.py                          # runs `pytest evals -m "not live"`, then writes the report
    uv run python evals/report.py --from run.jsonl         # writes the report from an earlier run's rows
    uv run python evals/report.py --out evals/REPORT.md --keep evals/results/final.jsonl

REPORT.md quotes only numbers found in the rows. Anything the run could not do is listed as not run.
"""

import argparse
import json
import os
import subprocess
import sys
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
DEFAULT_OUT = HERE / "REPORT.md"

Row = dict[str, Any]


def read_rows(path: Path) -> list[Row]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def run_pytest(results: Path, extra: list[str]) -> int:
    env = {**os.environ, "ECOZONE_EVAL_RESULTS": str(results)}
    cmd = ["uv", "run", "pytest", "evals", "--ignore=evals/tests", "-m", "not live", "-rxXs", *extra]
    sys.stdout.write("running: " + " ".join(cmd) + "\n")
    return subprocess.run(cmd, cwd=REPO, env=env, check=False).returncode


def short(nodeid: str) -> str:
    return nodeid.split("/")[-1]


def fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:,.3f}".rstrip("0").rstrip(".") if abs(value) < 1000 else f"{value:,.0f}"
    if isinstance(value, dict):
        return ", ".join(f"{k}: {fmt(v)}" for k, v in value.items())  # pyright: ignore[reportUnknownVariableType]
    if isinstance(value, list):
        return ", ".join(fmt(v) for v in value)  # pyright: ignore[reportUnknownVariableType]
    return str(value)


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def measures(rows: list[Row], prefix: str) -> list[Row]:
    return [r for r in rows if r["result"] == "measured" and r["test"].startswith(prefix)]


def build(rows: list[Row]) -> str:
    outcomes = [r for r in rows if r["subject"] == "outcome"]
    for o in outcomes:
        o["result"] = {"passed": "pass", "failed": "fail"}.get(o["result"], o["result"])
    session = {r["subject"]: r["value"] for r in rows if r["test"] == "session" and r["result"] == "measured"}
    bundle: dict[str, Any] = session.get("bundle", {})
    machine: dict[str, Any] = session.get("machine", {})
    first = rows[0] if rows else {}
    commit = str(first.get("commit", "unknown"))
    dirty = bool(first.get("dirty", False))
    run_at = min((r["run_at"] for r in rows), default="unknown")
    counts = defaultdict(int)
    for o in outcomes:
        counts[o["result"]] += 1

    out: list[str] = []
    out.append("# Evaluation report")
    out.append("")
    out.append(
        "Generated by `evals/report.py` from the rows a real run wrote. Every number below was produced by an eval in "
        "that run; nothing is a target or an estimate. Scores are the engine's 0-100 heuristic indices (VCI, HEI, GCS, "
        "PSS) and the Area Cooling Score (ACS)."
    )
    out.append("")
    out.append(f"- **Commit:** `{commit}`{' (working tree had uncommitted changes)' if dirty else ''}")
    out.append(f"- **Run at:** {run_at}")
    out.append(
        f"- **Bundle:** {bundle.get('name')} (`{bundle.get('area_id')}`), version `{bundle.get('bundle_version')}`, "
        f"reference date {bundle.get('reference_date')}, pipeline commit `{bundle.get('pipeline_git_sha')}`, "
        f"settings hash `{str(bundle.get('settings_hash'))[:12]}`"
    )
    out.append(f"- **Bundle source:** {bundle.get('bundle_note')}")
    c = bundle.get("counts") or {}
    out.append(
        f"- **Bundle size:** {fmt(c)}; blocks split {bundle.get('tune_blocks')} tune / "
        f"{bundle.get('test_blocks')} test "
        "(range results are reported on the test blocks; nothing here was tuned on either half)"
    )
    out.append(f"- **Machine:** {machine.get('platform')}, {machine.get('cpus')} CPUs, Python {machine.get('python')}")
    out.append(
        "- **Results by outcome:** "
        + ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
        + f" ({len(outcomes)} evals)"
    )
    if bundle.get("bundle_kind") == "tiny":
        out.append("")
        out.append("> **This report was produced on the tiny CI fixture, not on the Deccan bundle.**")
    out.append("")

    out.append("## Results")
    out.append("")
    order = {"fail": 0, "xpass": 1, "xfail": 2, "skip": 3, "pass": 4}
    rows_out = [
        [f"`{short(o['test'])}`", o["result"], f"{o['value']:.1f} seconds"]
        for o in sorted(outcomes, key=lambda o: (order.get(o["result"], 9), o["test"]))
    ]
    out += table(["Eval", "Result", "Time"], rows_out)
    out.append("")

    problems = [o for o in outcomes if o["result"] in ("fail", "xfail", "xpass")]
    out.append("## Failures and findings")
    out.append("")
    if not problems:
        out.append("No eval failed.")
    shown: set[tuple[str, str, str]] = set()
    for o in problems:
        out.append(f"### `{short(o['test'])}`: {o['result']}")
        out.append("")
        out.append(str(o.get("detail") or "(no detail recorded)"))
        out.append("")
        note = ANALYSIS.get(short(o["test"]).split("::")[-1].split("[")[0])
        if note:
            out.append(f"Analysis (from reading the code, not measured): {note}")
            out.append("")
        group = _group(o["test"])
        related = [
            m
            for m in rows
            if m["result"] == "measured"
            and m["test"].split(".")[0] == group
            and (group, m["test"], m["subject"]) not in shown
        ]
        for m in related:
            shown.add((group, m["test"], m["subject"]))
            out.append(f"- measured `{m['test']}` / `{m['subject']}`: {fmt(m['value'])}")
        out.append("")

    out.append("## Gemini vs greedy (offline rule proposer, not Gemini)")
    out.append("")
    out.append(
        "The search loop was run with `ECOZONE_LLM=fake`: the offline rule proposer stands in for the model, so these "
        "rows describe the loop and scorer, not Gemini. There is no pass mark. ACS is the area cooling score after the "
        "plan (higher is better); baseline is the area before any change. Outcome compares the best valid AI plan with "
        "the greedy plan by ACS (a difference under 0.05 is a tie). `Loop verdict` is the search's own "
        "`gemini_beat_greedy`, which also counts a greedy plan that breaks a rule as beaten."
    )
    out.append("")
    fake = measures(rows, "gemini_vs_greedy.fake")
    if fake:
        trs: list[list[str]] = []
        for m in fake:
            v = m["value"]
            trs.append(
                [
                    f"`{m['subject']}`",
                    f"{v['budget_inr']:,.0f}",
                    f"{v['quick_win_share_pct']:g}%",
                    f"{v['baseline_acs']:.2f}",
                    f"{v['greedy_acs']:.2f}"
                    + ("" if v["greedy_valid"] else f" (invalid: {v['greedy_invalid_reason']})"),
                    "none valid" if v["ai_acs"] is None else f"{v['ai_acs']:.2f}",
                    "n/a" if v["delta"] is None else f"{v['delta']:+.2f}",
                    v["outcome"],
                    str(v["reported_gemini_beat_greedy"]),
                    f"{v['ai_valid_candidates']}/{v['ai_candidates']}",
                ]
            )
        out += table(
            [
                "Case",
                "Budget (INR)",
                "Quick-win share",
                "Baseline ACS",
                "Greedy ACS",
                "AI ACS",
                "Delta",
                "Outcome",
                "Loop verdict",
                "Valid/all AI candidates",
            ],
            trs,
        )
        out.append("")
        for m in fake:
            reasons = m["value"].get("ai_invalid_reasons") or {}
            out.append(
                f"- `{m['subject']}`: AI candidates not valid: {fmt(reasons) if reasons else 'none'}; "
                f"rounds run: {m['value']['rounds']}; greedy plan cost {m['value']['greedy_cost_inr']:,} INR"
            )
        gaps = measures(rows, "budget.quick_win_gap")
        if gaps:
            out.append("")
            out.append("Greedy's quick-win spend against the share, per case:")
            out.append("")
            for m in gaps:
                out.append(f"- `{m['subject']}`: {fmt(m['value'])}")
    else:
        out.append("Not run.")
    out.append("")
    live = [m for m in measures(rows, "gemini_vs_greedy.live") if m["test"] == "gemini_vs_greedy.live"]
    out.append("### Live Gemini")
    out.append("")
    if live:
        used = measures(rows, "gemini_vs_greedy.live_settings")
        intro = (
            "Real Gemini on Vertex AI through the same loop and scorer. No pass mark. Each case is a single run and "
            "Gemini's output differs between runs (a repeat of the same case scored differently in testing), so the "
            "table says nothing about averages."
        )
        if used:
            intro += " Settings the run used: " + fmt(used[0]["value"]) + "."
        out.append(intro)
        out.append("")
        ltrs: list[list[str]] = []
        for m in live:
            v = m["value"]
            ltrs.append(
                [
                    f"`{m['subject']}`",
                    f"{v['budget_inr']:,.0f}",
                    f"{v['quick_win_share_pct']:g}%",
                    f"{v['baseline_acs']:.2f}",
                    f"{v['greedy_acs']:.2f}"
                    + ("" if v["greedy_valid"] else f" (invalid: {v['greedy_invalid_reason']})"),
                    "none valid" if v["ai_acs"] is None else f"{v['ai_acs']:.2f}",
                    "n/a" if v["delta"] is None else f"{v['delta']:+.2f}",
                    v["outcome"],
                    f"{v['ai_valid_candidates']}/{v['ai_candidates']}",
                    "n/a" if v["ai_cost_inr"] is None else f"{v['ai_cost_inr']:,.0f}",
                    f"{v['greedy_cost_inr']:,.0f}",
                ]
            )
        out += table(
            [
                "Case",
                "Budget (INR)",
                "Quick-win share",
                "Baseline ACS",
                "Greedy ACS",
                "Gemini ACS",
                "Delta",
                "Outcome",
                "Valid/all Gemini candidates",
                "Gemini plan cost (INR)",
                "Greedy plan cost (INR)",
            ],
            ltrs,
        )
        out.append("")
        for m in live:
            reasons = m["value"].get("ai_invalid_reasons") or {}
            out.append(f"- `{m['subject']}`: Gemini candidates not valid: {fmt(reasons) if reasons else 'none'}")
    else:
        out.append(
            "**Not run.** The live Gemini evals (`evals/test_live_gemini.py`, marker `live`) need Vertex AI "
            "credentials "
            "and `ECOZONE_LLM=gemini`; this run was offline. No Gemini number is reported."
        )
    out.append("")

    lprot = measures(rows, "protect_search.live")
    if lprot:
        out.append("### Protect design search (live Gemini)")
        out.append("")
        out.append("Worst change for each option (lower is better) and the share of floor area kept. No pass mark.")
        out.append("")
        lptr = [
            [f"`{m['subject']}`"]
            + [f"{m['value'][k]['worst_change']:.1f}, {m['value'][k]['floor_area_pct']:.0f}% floor area" for k in "ABC"]
            for m in lprot
        ]
        out += table(["Parcel", "A (as proposed)", "B", "C"], lptr)
        out.append("")

    prot = measures(rows, "protect_search.fake")
    if prot:
        out.append("### Protect design search (offline rule proposer)")
        out.append("")
        out.append("Worst change for each option (lower is better) and the share of floor area kept. No pass mark.")
        out.append("")
        ptr = []
        for m in prot:
            v = m["value"]
            ptr.append(
                [f"`{m['subject']}`"]
                + [
                    f"{v[k]['worst_change']:.2f} ({v[k]['risk_label']}), {v[k]['floor_area_pct']:.0f}% floor area"
                    for k in ("A", "B", "C")
                ]
            )
        out += table(["Parcel", "A (as proposed)", "B", "C"], ptr)
        out.append("")

    out.append("## Speed")
    out.append("")
    out.append(
        "Wall time with `time.perf_counter`, 20 repeated runs after one warm-up (10 for shadows and the empty "
        "rescore); "
        "targets are the numbers in docs/ENGINEERING_RULES.md section 8. Greedy: 5 runs at the mid budget. The search "
        "is one run."
    )
    out.append("")
    sp = [m for m in rows if m["result"] == "measured" and m["test"].startswith("speed.rescore")]
    sp += measures(rows, "speed.shadows")
    srows: list[list[str]] = []
    for m in sp:
        v = m["value"]
        srows.append(
            [
                f"{m['test'].split('.')[1]}: {m['subject']}",
                f"{v['p50_ms']:,.1f}",
                f"{v['p95_ms']:,.1f}",
                f"{v['min_ms']:,.1f} to {v['max_ms']:,.1f}",
                f"{v['target_ms']:,.0f}" if "target_ms" in v else "none",
                ("within" if v["p95_ms"] <= v["target_ms"] else "over") if "target_ms" in v else "",
            ]
        )
    other: list[list[str]] = []
    for m in measures(rows, "speed.greedy"):
        v = m["value"]
        if "p50_ms" in v:
            srows.append(
                [
                    f"greedy: {m['subject']} budget ({v['budget_inr']:,.0f} INR)",
                    f"{v['p50_ms']:,.0f}",
                    f"{v['p95_ms']:,.0f}",
                    f"{v['min_ms']:,.0f} to {v['max_ms']:,.0f}",
                    "none",
                    "",
                ]
            )
    if srows:
        out += table(["Step", "p50 (ms)", "p95 (ms)", "Range (ms)", "Target (ms)", "p95 vs target"], srows)
    out.append("")
    for m in (
        measures(rows, "speed.load_bundle")
        + measures(rows, "speed.search")
        + [m for m in measures(rows, "speed.greedy") if "p50_ms" not in m["value"]]
    ):
        other.append([f"{m['test'].split('.')[1]}: {m['subject']}", fmt(m["value"]), str(m.get("detail") or "")])
    if other:
        out += table(["Step", "Measured", "Note"], other)
        out.append("")

    out += heat_check_section(rows, outcomes, str(bundle.get("area_id")))

    out.append("## Other measured values")
    out.append("")
    skip_groups = ("session", "gemini_vs_greedy", "protect_search", "speed", "heat_check")
    groups: dict[str, list[Row]] = defaultdict(list)
    for m in rows:
        if m["result"] == "measured" and not m["test"].startswith(skip_groups):
            groups[m["test"]].append(m)
    for g in sorted(groups):
        out.append(f"**{g}**")
        out.append("")
        for m in groups[g]:
            note = f" ({m['detail']})" if m.get("detail") else ""
            out.append(f"- `{m['subject']}`: {fmt(m['value'])}{note}")
        out.append("")

    out.append("## Not run")
    out.append("")
    if measures(rows, "gemini_vs_greedy.live"):
        out.append(
            "- **Live grounding and tool-order runs on Gemini**: not run. Only Gemini vs greedy and the Protect "
            "options were run live."
        )
    else:
        out.append(
            "- **Live Gemini evals** (Gemini vs greedy with the real model, grounding and tool-order runs on "
            "Gemini): need Vertex AI credentials; not run here."
        )
    if not measures(rows, "heat_check."):
        out.append("- **Heat check**: not run; see the Heat check section. No correlation is reported.")
    skips = [o for o in outcomes if o["result"] == "skip"]
    for o in (o for o in skips if "test_heat_check" not in o["test"]):
        out.append(f"- `{short(o['test'])}` was skipped: {o.get('detail') or 'no reason recorded'}")
    out.append("")
    out.append("## How the search was driven")
    out.append("")
    out.append(
        "`evals/evalkit/adapter.py` hands the agents' search loop the engine's own public API (`summary`, `layer`, "
        "`single_site`, `rescore`, `greedy_baseline`). `rescore` is never cached. Greedy for each case and every "
        "offered site's single-site result are computed once in this process with the same engine functions and "
        "reused by the search runs, to save wall time. Search runs use a long time limit so the wall clock cannot "
        "change what a run does."
    )
    out.append("")
    return "\n".join(out) + "\n"


HEAT_CAVEATS = [
    "Surface temperature is not the air temperature people feel.",
    "The heat index shares inputs with what drives surface temperature (paving, green cover, built volume, roof "
    "reflectance), so agreement "
    "shows that the index ranks blocks sensibly, not that its weights are right.",
    "Landsat sees the top of a shade structure, not the shaded ground under it, so satellite data can never confirm "
    "that shade structures work.",
    "Landsat thermal bands are collected at 100 m and resampled to 30 m; a block of only a few pixels is a mixed "
    "measurement, and each block's valid pixel count is recorded.",
    "Each scene is one overpass in the late morning, not the afternoon peak.",
    "The test half is a small sample; read the block count and the p-value with it, not the correlation alone.",
]


def heat_check_section(rows: list[Row], outcomes: list[Row], area_id: str) -> list[str]:
    """The heat check section. Every number comes from rows the heat-check eval wrote; nothing here is typed in."""
    out = ["## Heat check", ""]
    primary = {m["subject"]: m["value"] for m in measures(rows, "heat_check.primary")}
    secondary = {m["subject"]: m["value"] for m in measures(rows, "heat_check.secondary")}
    prov = next((m["value"] for m in measures(rows, "heat_check.provenance")), None)
    if not primary or prov is None:
        ran = [o for o in outcomes if "test_heat_check" in o["test"]]
        reason = next((str(o.get("detail") or "") for o in ran if o["result"] in ("skip", "fail")), "")
        if any(o["result"] == "fail" for o in ran):
            out.append(
                "**Heat check: ran but failed its well-formedness checks, so no correlation is reported.** "
                "See Failures and findings."
            )
        else:
            prefix = "heat check: not run. "
            why = reason[len(prefix) :] if reason.startswith(prefix) else ""
            how = why or (
                f"Create the surface temperature table with `uv run --extra ee pipeline heat-check --area {area_id}` "
                "(needs Earth Engine access; see evals/heat_check/README.md)."
            )
            out.append(f"**Heat check: not run.** {how} Then rerun the evals. No correlation is reported.")
        out.append("")
        return out

    perms, seed = primary[next(iter(primary))]["permutations"], primary[next(iter(primary))]["seed"]
    out.append(
        "Does the baseline heat index (no changes applied) rank blocks the way measured satellite surface "
        "temperature does? Each block's median land surface temperature comes from cloud-free Landsat 8 and 9 scenes "
        "in March to May. The statistic is the Spearman rank correlation (ties share the average rank); the p-value "
        f"is two-sided from {perms:,} random re-pairings with a fixed seed ({seed}). A positive correlation means "
        "blocks with a higher heat index tend to have hotter surfaces. There is no pass mark: the result is reported "
        "as measured, and no weight, index or setting was changed or tuned after seeing it. The test half of the "
        "blocks is the held-out half and the headline."
    )
    out.append("")

    def split_rows(table: dict[str, Any], index: str, label: str) -> list[list[str]]:
        names = {"test": "test (held out, headline)", "all": "all blocks", "tune": "tune (context)"}
        return [
            [
                label,
                names[s],
                f"{v['n']} of {v['blocks_in_bundle']}",
                f"{v['rho']:+.3f}",
                f"{v['p_value']:.4f}",
            ]
            for s in ("test", "all", "tune")
            if (v := table.get(f"{index}:{s}"))
        ]

    out.append("### Heat index (primary)")
    out.append("")
    out += table(
        ["Index", "Blocks", "Count (of bundle blocks)", "Spearman rho", "Permutation p"],
        split_rows(primary, "hei", "HEI"),
    )
    out.append("")
    if secondary:
        out.append("### Other indices (secondary)")
        out.append("")
        out.append(
            "Declared before the first run and reported for context only. The heat index is the one the check is "
            "about; only it is described as validated here. These are not corrected for multiple comparisons."
        )
        out.append("")
        srows: list[list[str]] = []
        for idx in ("vci", "gcs", "pss"):
            srows += split_rows(secondary, idx, idx.upper())
        out += table(["Index", "Blocks", "Count (of bundle blocks)", "Spearman rho", "Permutation p"], srows)
        out.append("")

    out.append("### Satellite data")
    out.append("")
    out.append(
        "- **Datasets:** " + ", ".join(f"`{d}`" for d in prov["datasets"]) + ", band ST_B10 (surface temperature)"
    )
    for w in prov["windows"]:
        per = ", ".join(f"`{d}` {n}" for d, n in w["scenes"].items())
        out.append(f"- **Window {w['year']}:** {w['start']} to {w['end']}; scenes: {per}")
    years = ", ".join(str(y) for y in prov["years_used"])
    extra = (
        " (the year before was added because the reference year had too few scenes)"
        if len(prov["years_used"]) > 1
        else ""
    )
    out.append(f"- **Years used:** {years}{extra}")
    met = "met" if prov["min_scenes_met"] else "NOT met"
    out.append(
        f"- **Scenes used:** {prov['scenes_total']} scenes (minimum {prov['min_scenes']}: {met}); "
        "per-pixel median over the window"
    )
    out.append(
        f"- **Screening:** scenes over {prov['scene_max_cloud_cover_pct']:g}% cloud cover excluded; cloud, cloud "
        "shadow, dilated cloud and cirrus pixels masked; pixels the product's own per-pixel uncertainty band marks "
        "as unreliable masked (the limit is our own choice, set before the run and recorded in the data file's "
        "provenance)"
    )
    out.append(
        f"- **Aggregation:** median over each block at {prov['scale_m']} m "
        f"(native thermal resolution {prov['native_thermal_resolution_m']} m)"
    )
    out.append(
        f"- **Blocks:** {prov['blocks_with_lst']} of {prov['blocks_requested']} blocks had a valid pixel "
        f"({prov['blocks_dropped']} dropped); valid pixels per block "
        f"(coverage-weighted): minimum {prov['valid_pixels_min']:g}, median {prov['valid_pixels_median']:g}, "
        f"maximum {prov['valid_pixels_max']:g}"
    )
    out.append(f"- **Fetched:** {prov['fetch_date']} from Earth Engine project `{prov['earth_engine_project']}`")
    if not (prov["bundle_version_matches"] and prov["bundle_settings_hash_matches"]):
        out.append(
            "- **Warning:** the surface temperature table was made from a different bundle build than the one scored "
            "here (version or settings hash differ); block ids matched, but the geometry may not."
        )
    out.append("")
    out.append("### Caveats")
    out.append("")
    out += [f"- {c}" for c in HEAT_CAVEATS]
    out.append("")
    return out


ANALYSIS = {
    "test_search_returns_a_valid_plan": (
        "see the quick-win gap rows below: the greedy plan's quick-win spend ends under the share by a sum smaller "
        "than any left-out quick-win site, so the loop (which requires the full share) marks it invalid. "
        "engine/greedy.py phase 1 refuses any quick win that would take the quick-win spend over the share "
        "(`quick_spent + cost > quick_win_budget`), takes minimum quantities only and never tops up past the share, "
        "and phase 2 then spends the rest of the budget on the best sites of any kind, so it reaches the share only "
        "by luck; agents/repair.py `_invalid_reason` is a plain `>=` check against the planner's share, "
        "which matches PLANNING.md ('at least the share'). The gap is therefore in greedy's phase "
        "logic, not in how the loop reads the share."
    ),
}


def _group(nodeid: str) -> str:
    name = short(nodeid).split("::")[0]
    return name.removeprefix("test_").removesuffix(".py").split("_")[0]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="source", type=Path, help="write the report from this JSONL instead of running")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--keep", type=Path, help="also copy the rows to this path (the committed final run)")
    ap.add_argument("pytest_args", nargs="*", help="extra arguments for pytest")
    args = ap.parse_args()

    if args.source:
        results = args.source
        code = 0
    else:
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        results = HERE / "results" / f"run-{stamp}.jsonl"
        code = run_pytest(results, args.pytest_args)
    rows = read_rows(results)
    if not rows:
        sys.stderr.write("no rows were written; nothing to report\n")
        return 2
    args.out.write_text(build(rows))
    if args.keep:
        args.keep.write_text(results.read_text())
    sys.stdout.write(f"wrote {args.out} from {results} (pytest exit code {code})\n")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
